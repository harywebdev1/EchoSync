const assert = require('node:assert/strict')
module.exports = async function verifyProductionOverhaul({ check, open }) {
  for (const [width, height] of [[360,780],[390,844],[1440,900]]) {
    await check(`Production ${width}: long queue, Library actions, chat opacity, activity and paused Resync`, {}, async page => {
      await page.setViewportSize({width,height})
      await page.addInitScript(() => {
        const library=JSON.parse(localStorage.getItem('echosync.library.v1'))
        const seed=library.chaleya.track
        const ids=['chaleya',...Array.from({length:26},(_,i)=>'audit-track-'+i)]
        for(const id of ids.slice(1)) library[id]={savedAt:Date.now(),track:{...seed,id,title:'Audit track '+id.split('-').at(-1),streamUrl:'https://aac.saavncdn.com/integrity/'+id+'.wav?seconds=180'}}
        localStorage.setItem('echosync.library.v1',JSON.stringify(library))
        localStorage.setItem('echosync_playlists_v1',JSON.stringify({integrity:[{id:'audit-list',name:'Audit collection',trackIds:ids,visibility:'private'}]}))
        localStorage.setItem('echosync.likes.v1',JSON.stringify({integrity:['chaleya','excuses']}))
        const rooms=JSON.parse(localStorage.getItem('echosync_rooms_v3')); rooms[0].trackIds=ids;localStorage.setItem('echosync_rooms_v3',JSON.stringify(rooms))
        localStorage.setItem('echosync_public_lounge_v1',JSON.stringify([{id:'expired',author:'integrity',text:'Expired audit message',createdAt:Date.now()-86400001},{id:'fresh',author:'integrity',text:'Fresh audit message',createdAt:Date.now()}]))
      })
      await open(page)
      if(process.env.ECHOSYNC_SCREENSHOTS) await page.screenshot({animations:'disabled',path:`performance-results.local/production-home-${width}.png`})
      await page.locator('.quick-picks-section').scrollIntoViewIfNeeded()
      const geometry=await page.waitForFunction(()=>{
        const row=[...document.querySelectorAll('.quick-card')].find(el=>{const box=el.getBoundingClientRect();return box.width>0&&box.height>0&&box.x>=0&&box.right<=innerWidth&&box.top>=0&&box.bottom<=innerHeight})
        if(!row)return false
        const box=row.getBoundingClientRect(), actions=row.querySelector('.quick-actions').getBoundingClientRect()
        if(!actions.width)return false
        return {gap:box.right-actions.right,height:box.height}
      })
      const quick=await geometry.jsonValue()
      assert.ok(quick.gap<=18, JSON.stringify(quick)); assert.ok(quick.height>=55 && quick.height<=57,JSON.stringify(quick))
      const nav=page.locator(width<=768?'.mobile-bottom-bar':'.sidebar')
      await nav.getByRole('button',{name:/Your library|Library/i}).click()
      const create=page.locator('.library-hero .library-head-actions').getByRole('button',{name:'New playlist'})
      assert.ok((await create.boundingBox()).width>90)
      if(process.env.ECHOSYNC_SCREENSHOTS) await page.screenshot({animations:'disabled',path:`performance-results.local/production-library-${width}.png`})
      await page.locator('.playlist-card').filter({hasText:'Audit collection'}).click()
      await page.locator('.playlist-detail .primary-btn').click()
      await page.waitForFunction(()=>!document.querySelector('[data-testid=root-audio]').paused)
      const root=await page.getByTestId('root-audio').elementHandle()
      await page.getByRole('button',{name:'Open full player',exact:true}).filter({visible:true}).click()
      if(width<=768) {
        await page.getByRole('tab',{name:'Up Next',exact:true}).click()
        assert.equal(await page.locator('.fp-queue-row').count(),26)
        const scroll=await page.locator('.fp-body').evaluate(el=>{el.scrollTop=el.scrollHeight;return {top:el.scrollTop,last:el.querySelector('.fp-queue-row:last-child').getBoundingClientRect().bottom,bottom:el.getBoundingClientRect().bottom}})
        assert.ok(scroll.top>0,JSON.stringify(scroll));assert.ok(scroll.last<=scroll.bottom+1,JSON.stringify(scroll))
        if(process.env.ECHOSYNC_SCREENSHOTS) await page.screenshot({animations:'disabled',path:`performance-results.local/production-upnext-${width}.png`})
      }
      await page.getByRole('button',{name:'Close full player',exact:true}).click()
      if(width<=768) await nav.getByRole('button',{name:'Account',exact:true}).click()
      else await page.locator('.sidebar .profile').click()
      await page.getByRole('button',{name:'Settings',exact:true}).click()
      const settings=page.getByRole('dialog')
      assert.equal(await settings.locator('.signout-btn').evaluate(el=>getComputedStyle(el).position),'static')
      await page.getByRole('button',{name:'Close settings',exact:true}).click()
      await page.getByRole('button',{name:'Notifications',exact:true}).click()
      await page.getByRole('region',{name:'Recent activity and notifications'}).waitFor()
      await page.getByRole('button',{name:'Clear all',exact:true}).click()
      await page.getByRole('button',{name:'Close notifications',exact:true}).filter({visible:true}).last().click()
      await page.getByTestId('lounge-header-btn').click()
      await page.getByTestId('lounge-drawer').waitFor()
      assert.equal(await page.getByText('Expired audit message',{exact:true}).count(),0)
      await page.getByText('Fresh audit message',{exact:true}).waitFor()
      if(width<=768) assert.match(await page.getByTestId('lounge-drawer').evaluate(el=>getComputedStyle(el).backgroundColor),/0\.96\)/)
      await page.getByTestId('lounge-close-btn').click()
      if(width<=768) { await nav.getByRole('button',{name:'Rooms',exact:true}).click();await page.locator('.room-card').filter({hasText:'Integrity Room'}).click() }
      else await page.locator('.sidebar').getByRole('button',{name:/Integrity Room/}).first().click()
      await page.getByRole('button',{name:'Import playlist',exact:true}).click()
      await page.getByRole('dialog').getByRole('heading',{name:'Import playlist',exact:true}).waitFor()
      await page.getByRole('button',{name:'Close import',exact:true}).click()
      await page.locator('.room-chat-entry').first().click()
      await page.locator('.social.mobile-open:not(.lounge-drawer)').waitFor()
      if(process.env.ECHOSYNC_SCREENSHOTS) await page.screenshot({animations:'disabled',path:`performance-results.local/production-chat-${width}.png`})
      await page.locator('.social.mobile-open:not(.lounge-drawer) .social-close').click()
      const pause=page.locator('.player-dock').getByRole('button',{name:'Pause',exact:true})
      if(await pause.count()) await pause.click()
      else { const mobilePause=page.locator('.mobile-mini').getByRole('button',{name:'Pause',exact:true});if(await mobilePause.count())await mobilePause.click() }
      await page.locator('.room-sync-actions').getByRole('button',{name:'Resync',exact:true}).click()
      assert.equal(await page.getByTestId('root-audio').evaluate(audio=>audio.paused),true)
      assert.equal(await page.getByTestId('root-audio').evaluate((audio,old)=>audio===old,root),true)
      assert.equal(await page.locator('iframe').count(),0)
      console.log(`Production geometry ${width}`,JSON.stringify(quick))
    })
  }
  await check('Production native ended handoff plays the exact prewarmed next URL in the ended event tick', {}, async page => {
    await page.addInitScript(() => {
      const library=JSON.parse(localStorage.getItem('echosync.library.v1'))
      localStorage.setItem('echosync_playlists_v1',JSON.stringify({integrity:[{id:'handoff',name:'Native handoff',trackIds:['chaleya','excuses']}]}))
      window.__nativePlays=[];window.__warmAudio=[]
      const NativeAudio=window.Audio
      window.Audio=function(...args){const audio=new NativeAudio(...args);window.__warmAudio.push(audio);return audio}
      window.Audio.prototype=NativeAudio.prototype
      const play=HTMLMediaElement.prototype.play
      HTMLMediaElement.prototype.play=function(...args){if(this.dataset.testid==='root-audio')window.__nativePlays.push({src:this.src,endedTick:window.event?.type === 'ended'});return play.apply(this,args)}
      void library
    })
    await open(page)
    await page.locator('.sidebar').getByRole('button',{name:/Your library|Library/i}).click()
    await page.locator('.playlist-card').filter({hasText:'Native handoff'}).click()
    await page.locator('.playlist-detail .primary-btn').click()
    await page.waitForFunction(()=>!document.querySelector('[data-testid=root-audio]').paused)
    const root=await page.getByTestId('root-audio').elementHandle()
    await page.waitForFunction(()=>window.__warmAudio.some(audio=>audio.src.includes('/excuses.wav')&&audio.readyState>=1))
    const foreground=await page.context().newPage()
    await foreground.bringToFront()
    console.log('Native handoff page visibility',await page.evaluate(()=>document.visibilityState))
    await page.getByTestId('root-audio').evaluate(audio=>{audio.currentTime=audio.duration-.15})
    await page.waitForFunction(()=>document.querySelector('[data-testid=root-audio]').currentSrc.includes('/excuses.wav')&&!document.querySelector('[data-testid=root-audio]').paused&&document.querySelector('[data-testid=root-audio]').readyState>=2&&document.querySelector('[data-testid=root-audio]').currentTime>.05, null, {polling:100})
    assert.ok(await page.evaluate(()=>window.__nativePlays.some(play=>play.src.includes('/excuses.wav')&&play.endedTick)), JSON.stringify(await page.evaluate(()=>window.__nativePlays)))
    assert.equal(await page.getByTestId('root-audio').evaluate((audio,old)=>audio===old,root),true)
    assert.ok(await page.evaluate(()=>navigator.mediaSession.metadata?.title))
  })
  await check('Production Liked context, orphaned likes, album sheet and bounded startup feed', {}, async page => {
    const requests=[]
    page.on('request',request=>{if(request.url().includes('/api/ytmusic'))requests.push(request.url())})
    await page.addInitScript(()=>localStorage.setItem('echosync.likes.v1',JSON.stringify({integrity:['chaleya','excuses','missing-liked-id']})))
    await open(page)
    await page.waitForTimeout(1500)
    assert.ok(requests.length<=3, JSON.stringify(requests))
    console.log('Startup catalog requests',requests.length)
    assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('echosync.likes.v1')).integrity.some(item=>(item.id||item)==='missing-liked-id')))
    await page.locator('.sidebar').getByRole('button',{name:/Your library|Library/i}).click()
    await page.getByRole('button',{name:'Liked songs',exact:true}).click()
    await page.locator('.library-row').filter({hasText:'Chaleya'}).first().click()
    await page.waitForFunction(()=>!document.querySelector('[data-testid=root-audio]').paused)
    await page.getByTestId('queue-btn').click()
    await page.getByTestId('solo-queue-drawer').waitFor()
    assert.equal(await page.getByTestId('queue-drawer-row').count(),1)
    assert.match(await page.getByTestId('queue-drawer-row').innerText(),/Excuses/)
    await page.getByRole('button',{name:'Close queue',exact:true}).click()
    await page.route('**/api/ytmusic?*',async route=>{
      const url=new URL(route.request().url())
      const songs=[{videoId:'chaleyaXXXX',title:'Chaleya',artist:'Arijit Singh',duration:180},{videoId:'excusesXXXX',title:'Excuses',artist:'AP Dhillon',duration:180}]
      if(url.searchParams.get('action')==='artist')return route.fulfill({contentType:'application/json',body:JSON.stringify({name:'Arijit Singh',browseId:'UCfixture123',songs,albums:[{name:'Audit Album',browseId:'MPREfixture123'}]})})
      if(url.searchParams.get('action')==='album')return route.fulfill({contentType:'application/json',body:JSON.stringify({browseId:'MPREfixture123',songs})})
      return route.fallback()
    })
    const source=await page.getByTestId('root-audio').evaluate(audio=>audio.currentSrc)
    await page.locator('.library-row').filter({hasText:'Chaleya'}).locator('.artist-link').first().click()
    await page.getByRole('button',{name:'Open Audit Album',exact:true}).click()
    const album=page.getByRole('dialog')
    await album.getByRole('heading',{name:'Audit Album',exact:true}).waitFor()
    assert.equal(await album.locator('.fp-queue-row').count(),2)
    assert.equal(await page.getByTestId('root-audio').evaluate(audio=>audio.currentSrc),source)
    await album.getByRole('button',{name:'▶ Play Album',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.dock-title')?.textContent?.includes('Chaleya')||document.querySelector('.dock-copy')?.textContent?.includes('Chaleya'))
    await album.getByRole('button',{name:'Close',exact:true}).click()
    await page.getByTestId('queue-btn').click()
    await page.getByTestId('solo-queue-drawer').waitFor()
    assert.equal(await page.getByTestId('queue-drawer-row').count(),1)
  })
  await check('Production activity bell retains the last 15 structured invitations and clears unread state', {}, async page=>{
    await open(page)
    await page.evaluate(()=>{
      window.__notificationPeer=new BroadcastChannel('echosync-room-sync')
      for(let index=0;index<20;index++)window.__notificationPeer.postMessage({type:'room-invite',sender:'notification-peer',invite:{id:'activity-'+index,toUserId:'integrity',fromHandle:'peer',roomId:'integrity-room',roomName:'Integrity Room'}})
    })
    await page.locator('.es-toast-card').waitFor()
    await page.locator('.notification-unread').waitFor()
    await page.getByRole('button',{name:'Notifications',exact:true}).click()
    await page.waitForFunction(()=>document.querySelectorAll('.notification-popover article').length===15)
    assert.equal(await page.locator('.notification-unread').count(),0)
    assert.ok(await page.locator('.notification-popover article').first().getByRole('button',{name:'Join',exact:true}).count())
    await page.getByRole('button',{name:'Clear all',exact:true}).click()
    assert.equal(await page.locator('.notification-popover article').count(),0)
    await page.evaluate(()=>window.__notificationPeer.close())
  })
  await check('Production Room radio appends real catalog candidates and advances with honest upcoming counts', {trackOverrides:{chaleya:{youtubeVideoId:'chaleyaXXXX'}}}, async page=>{
    await page.addInitScript(()=>{const rooms=JSON.parse(localStorage.getItem('echosync_rooms_v3'));rooms[0].trackIds=['chaleya'];localStorage.setItem('echosync_rooms_v3',JSON.stringify(rooms))})
    await page.route('**/api/ytmusic?*',route=>{
      if(new URL(route.request().url()).searchParams.get('action')!=='radio')return route.fallback()
      return route.fulfill({contentType:'application/json',body:JSON.stringify({songs:[{videoId:'excusesXXXX',title:'Excuses',artist:'AP Dhillon',duration:180},{videoId:'kesariyaXXX',title:'Kesariya',artist:'Arijit Singh',duration:180}]})})
    })
    await open(page)
    await page.locator('.sidebar').getByRole('button',{name:/Integrity Room/}).first().click()
    await page.locator('.room-head').waitFor()
    const warmed=page.waitForResponse(response=>response.url().includes('excuses.wav'))
    await page.locator('.player-dock').getByRole('button',{name:'Play',exact:true}).click()
    await page.locator('.room-queue .queue-row').filter({hasText:'Excuses'}).waitFor()
    assert.match(await page.locator('.room-queue-header .source-badge').innerText(),/2 upcoming/i)
    await warmed
    await page.getByTestId('root-audio').evaluate(audio=>{audio.currentTime=audio.duration-.15})
    await page.waitForFunction(()=>document.querySelector('[data-testid=root-audio]').currentSrc.includes('excuses.wav')&&!document.querySelector('[data-testid=root-audio]').paused&&document.querySelector('[data-testid=root-audio]').readyState>=2&&document.querySelector('[data-testid=root-audio]').currentTime>.05)
    assert.match(await page.locator('.room-queue-header .source-badge').innerText(),/1 upcoming/i)
    assert.equal(await page.locator('.room-queue .queue-row').count(),2)
  })
}
