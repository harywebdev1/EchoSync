async function context(browser, size, type = 'synced') {
  const state = fixtureState({}), entries = state.origins[0].localStorage
  entries.push({ name: 'echosync_playlists_v1', value: JSON.stringify({ integrity: [{ id: 'empty-playlist', name: 'Evening collection', trackIds: [] }] }) })
  const data = { type, language: 'en', translatable: false, lines: [ { time: 0, text: 'A little light across the room' }, { time: 22, text: 'The melody finds its way home' }, { time: 40, text: 'Stay here for another song' } ] }
  entries.push({ name: 'echosync.lyrics.v1', value: JSON.stringify({ 'chaleya::arijit singh': { savedAt: Date.now(), data } }) })
  const ctx = await browser.newContext({ viewport: size, storageState: state }); await installFixtures(ctx)
  const page = await ctx.newPage(), errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(URL, { waitUntil: 'domcontentloaded' }); await page.locator('.quick-main').first().waitFor()
  return { ctx, page, errors }
}
